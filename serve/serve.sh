#!/usr/bin/env bash
# Serve a Nenya checkpoint with vLLM's OpenAI-compatible server: /v1/chat/completions (tools, streaming),
# /v1/completions, /v1/models, /tokenize.
#
#   serve/serve.sh /models/nenya-base [extra `vllm serve` args]
#
# Environment (all optional):
#   SERVED_MODEL_NAME  model name clients send                      (default: nenya)
#   HOST / PORT        bind address                                 (default: 0.0.0.0 / 8000)
#   MAX_MODEL_LEN      context length served                        (default: 16384, Nenya's trained length)
#   MAX_NUM_BATCHED_TOKENS  tokens per engine step                  (default: 8192; vLLM's own default for
#                      `vllm serve` on GPUs under 70 GB is 2048, which on an RTX 5090 gives 2.5x less throughput
#                      and 5x the p99 time-to-first-token at 256 concurrent requests on an RTX 5090)
#   GENERATION_CONFIG  "auto" = the checkpoint's generation_config.json, or a directory holding one; vLLM takes
#                      the stop ids (eos_token_id) and default sampling from it  (default: auto)
#   CHAT_TEMPLATE      chat template file                           (default: the one packaged with nenya_vllm:
#                      Nenya's chat format, generated by nenya_vllm/olmo3_chat.py)
#   NENYA_PREFLIGHT    0 skips the check before vLLM starts         (default: 1; `python -m nenya_vllm.preflight`:
#                      the generation config's stop ids include <|im_end|> and <|endoftext|>, and the tokenizer
#                      names ids 100270/100271 <raw_code>/</raw_code>; the server is not started if either fails)
#   NENYA_MIDDLEWARE   0 leaves out nenya_vllm.serving's middleware (default: 1; it unescapes replies to requests
#                      without tools and refuses a conversation that ends with an assistant message)
# Needs the nenya-vllm package installed in the active Python environment (pip install <this repo>), and a
# checkpoint patched once with `python -m nenya_vllm.olmo3_chat export-hf MODEL_DIR` (names ids 100270/100271
# <raw_code>/</raw_code>, sets the stop ids, writes chat_template.jinja); the preflight stops the start if it was not.
set -euo pipefail
MODEL=${1:?usage: serve.sh MODEL_DIR_OR_HF_ID [extra vllm serve args]}
shift
TEMPLATE=${CHAT_TEMPLATE:-$(python3 -c "import nenya_vllm; print(nenya_vllm.chat_template_path())")}
if [ "${NENYA_PREFLIGHT:-1}" != 0 ]; then
    python3 -m nenya_vllm.preflight "$MODEL" --generation-config "${GENERATION_CONFIG:-auto}" \
        || { echo "serve.sh: preflight failed (NENYA_PREFLIGHT=0 starts the server anyway)" >&2; exit 1; }
fi
MIDDLEWARE=()
if [ "${NENYA_MIDDLEWARE:-1}" != 0 ]; then
    MIDDLEWARE=(--middleware nenya_vllm.serving.NenyaServingMiddleware)
fi
exec vllm serve "$MODEL" \
    --served-model-name "${SERVED_MODEL_NAME:-nenya}" \
    --chat-template "$TEMPLATE" \
    --enable-auto-tool-choice --tool-call-parser nenya \
    --generation-config "${GENERATION_CONFIG:-auto}" \
    --max-model-len "${MAX_MODEL_LEN:-16384}" \
    --max-num-batched-tokens "${MAX_NUM_BATCHED_TOKENS:-8192}" \
    --host "${HOST:-0.0.0.0}" --port "${PORT:-8000}" \
    ${MIDDLEWARE[@]+"${MIDDLEWARE[@]}"} \
    "$@"
