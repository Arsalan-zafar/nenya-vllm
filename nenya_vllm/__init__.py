"""vLLM plugin for Nenya-2.5B-A0.5B.

Installed as the `nenya` entry point of the `vllm.general_plugins` group, so vLLM calls `register()` in every
process (API server, engine core, workers) before it reads any model config. Importing this package itself does
not import vLLM or touch CUDA.
"""

import os

__version__ = "0.1.0.dev0"


def chat_template_path() -> str:
    """The packaged chat template, for `vllm serve --chat-template`: Nenya's chat format (OLMo 3 Instruct with
    Nenya's conventions), generated by olmo3_chat.py."""
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "olmo3_chat_template.jinja")


def register() -> None:
    from .registration import register_all

    register_all()
